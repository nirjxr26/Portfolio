import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ICONS_DIR = fileURLToPath(new URL("../public/icons/", import.meta.url));
const OUT_FILE = fileURLToPath(new URL("../src/lib/icon-versions.generated.ts", import.meta.url));

function walk(dir, out) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      walk(full, out);
    } else {
      out.push(full);
    }
  }
}

const files = [];
walk(ICONS_DIR, files);

const versions = {};
for (const file of files) {
  const urlPath = "/icons/" + relative(ICONS_DIR, file).split(sep).join("/");
  const content = readFileSync(file);
  const hash = createHash("sha1").update(content).digest("hex").slice(0, 8);
  versions[urlPath] = hash;
}

const body =
  "// AUTO-GENERATED by scripts/gen-icon-version.mjs - do not edit.\n" +
  "export const ICON_VERSIONS: Record<string, string> = " +
  JSON.stringify(versions, null, 2) +
  ";\n";

writeFileSync(OUT_FILE, body);
console.log(`[icon-version] hashed ${files.length} icon files -> ${OUT_FILE}`);
